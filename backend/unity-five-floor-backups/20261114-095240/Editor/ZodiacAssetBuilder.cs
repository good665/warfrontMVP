        const string Folder="Assets/Resources/Zodiac";
        static readonly string[] Names={"rat","ox","tiger","rabbit","dragon","snake","horse","goat","monkey","rooster","dog","pig","boss"};
        static readonly Color[] Fur={new Color(.48f,.44f,.56f),new Color(.55f,.30f,.15f),new Color(1,.5f,.10f),new Color(.91f,.86f,.94f),new Color(.12f,.65f,.44f),new Color(.30f,.64f,.18f),new Color(.58f,.25f,.13f),new Color(.86f,.79f,.57f),new Color(.45f,.23f,.12f),new Color(.92f,.78f,.36f),new Color(.76f,.56f,.31f),new Color(.97f,.56f,.61f),new Color(.31f,.12f,.48f)};
        [InitializeOnLoadMethod] static void AutoBuild(){EditorApplication.delayCall+=()=>{if(!File.Exists(Folder+"/generated-v1.txt")&&!EditorApplication.isPlayingOrWillChangePlaymode)Build();};}
        [MenuItem("Warfront/Five Floor/Build Zodiac Assets")]
        public static void Build()
        {
            try
            {
                Directory.CreateDirectory(Folder);
                for(int i=0;i<Names.Length;i++)BuildAnimal(i);
                File.WriteAllText(Folder+"/generated-v1.txt","Original Warfront zodiac animal meshes, palette UV textures, Generic rigs and legacy clips. Generated by ZodiacAssetBuilder. No external source assets.");
                AssetDatabase.Refresh();AssetDatabase.SaveAssets();Verify();RenderCatalog();
                File.WriteAllText(Path.Combine(Path.GetTempPath(),"warfront-five-floor-assets.result"),"PASS: 13 native prefabs; weighted meshes, UV textures, URP materials, Idle/Walk/Attack/Heavy/Dodge/Bow/Throw clips; baked deformation verified.");
            }
            catch(Exception e){Debug.LogException(e);File.WriteAllText(Path.Combine(Path.GetTempPath(),"warfront-five-floor-assets.result"),"FAIL: "+e);}
        }
        sealed class Geometry
        {
            public readonly List<Vector3> vertices=new List<Vector3>();public readonly List<Vector2> uv=new List<Vector2>();
            public readonly List<int> indices=new List<int>();public readonly List<BoneWeight> weights=new List<BoneWeight>();
            public void Oval(Vector3 center,Vector3 size,int bone,int color,int sides=8,int rings=5)
            {
                int start=vertices.Count;
                for(int r=0;r<=rings;r++)
                {
                    float latitude=Mathf.PI*r/rings;
                    for(int s=0;s<=sides;s++)
                    {
                        float longitude=2*Mathf.PI*s/sides;
                        vertices.Add(center+Vector3.Scale(new Vector3(Mathf.Sin(latitude)*Mathf.Cos(longitude),Mathf.Cos(latitude),Mathf.Sin(latitude)*Mathf.Sin(longitude)),size*.5f));
                        uv.Add(new Vector2((color+.5f)/8f,.5f));weights.Add(new BoneWeight{boneIndex0=bone,weight0=1});
                        if(r<rings&&s<sides){int a=start+r*(sides+1)+s,b=a+sides+1;indices.AddRange(new[]{a,a+1,b,a+1,b+1,b});}
                    }
                }
            }
            public void Cone(Vector3 center,float height,float radius,int bone,int color,bool down=false)
            {
                int start=vertices.Count;
                for(int i=0;i<8;i++)
                {
                    float a=i*Mathf.PI/4;vertices.Add(center+new Vector3(Mathf.Cos(a)*radius,0,Mathf.Sin(a)*radius));
                    uv.Add(new Vector2((color+.5f)/8,.5f));weights.Add(new BoneWeight{boneIndex0=bone,weight0=1});
                }
                vertices.Add(center+Vector3.up*height*(down?-1:1));uv.Add(new Vector2((color+.5f)/8,.5f));weights.Add(new BoneWeight{boneIndex0=bone,weight0=1});
                for(int i=0;i<8;i++)if(down)indices.AddRange(new[]{start+i,start+(i+1)%8,start+8});else indices.AddRange(new[]{start+(i+1)%8,start+i,start+8});
            }
        }
        static Transform Bone(string name,Transform parent,Vector3 position,List<Transform> bones)
        {var go=new GameObject(name);go.transform.SetParent(parent,false);go.transform.localPosition=position;bones.Add(go.transform);return go.transform;}
        static void BuildAnimal(int index)
        {
            string name=Names[index],path=Folder+"/"+name;Directory.CreateDirectory(path);AssetDatabase.Refresh();
            var texture=new Texture2D(16,2,TextureFormat.RGBA32,false){filterMode=FilterMode.Point,wrapMode=TextureWrapMode.Clamp};
            Color[] palette={Fur[index],new Color(.96f,.85f,.68f),new Color(.10f,.065f,.12f),Color.white,new Color(.98f,.46f,.53f),new Color(.95f,.74f,.2f),Fur[index]*.65f,new Color(.31f,.8f,.95f)};
            for(int x=0;x<16;x++)for(int y=0;y<2;y++)texture.SetPixel(x,y,palette[x/2]);texture.Apply();
            File.WriteAllBytes(path+"/Palette.png",texture.EncodeToPNG());UnityEngine.Object.DestroyImmediate(texture);AssetDatabase.ImportAsset(path+"/Palette.png");
            var importer=(TextureImporter)AssetImporter.GetAtPath(path+"/Palette.png");importer.filterMode=FilterMode.Point;importer.textureCompression=TextureImporterCompression.Uncompressed;importer.mipmapEnabled=false;importer.SaveAndReimport();
            var material=AssetDatabase.LoadAssetAtPath<Material>(path+"/Animal.mat");
            if(material==null){material=new Material(Shader.Find("Universal Render Pipeline/Lit"));AssetDatabase.CreateAsset(material,path+"/Animal.mat");}
            material.mainTexture=AssetDatabase.LoadAssetAtPath<Texture2D>(path+"/Palette.png");material.SetFloat("_Smoothness",.1f);material.SetFloat("_Cull",0);
            var root=new GameObject(name+" animal");var bones=new List<Transform>();
            var skeleton=Bone("root",root.transform,Vector3.zero,bones);
            var torso=Bone("torso",skeleton,new Vector3(0,.61f,0),bones);
            var head=Bone("head",torso,new Vector3(0,.22f,.36f),bones);
            for(int leg=0;leg<4;leg++)Bone("leg-"+leg,torso,new Vector3(leg%2==0?-.23f:.23f,-.11f,leg<2?.25f:-.28f),bones);
            var tail=Bone("tail",torso,new Vector3(0,.06f,-.46f),bones);
            var g=new Geometry();bool reptile=name=="dragon"||name=="boss",snake=name=="snake",bird=name=="rooster";
            float bodyLength=name=="horse"?1.1f:name=="pig"?1f:snake?1.65f:.88f;
            g.Oval(new Vector3(0,.62f,0),new Vector3(name=="pig"?.7f:.57f,snake?.30f:.56f,bodyLength),1,0);
            g.Oval(new Vector3(0,.54f,.13f),new Vector3(.47f,.38f,.57f),1,1);
            Vector3 hc=head.position;
            g.Oval(hc,new Vector3(name=="pig"?.55f:.48f,.46f,.48f),2,0);
            g.Oval(hc+new Vector3(0,-.09f,.24f),new Vector3(name=="horse"?.30f:.33f,.22f,name=="horse"?.43f:.26f),2,name=="pig"?4:1);
            foreach(float side in new[]{-1f,1f})
            {
                g.Oval(hc+new Vector3(side*.21f,.05f,.15f),new Vector3(.08f,.10f,.055f),2,3);
                g.Oval(hc+new Vector3(side*.22f,.05f,.177f),new Vector3(.045f,.07f,.025f),2,2);
                if(name=="rabbit")
                {g.Oval(hc+new Vector3(side*.15f,.39f,-.015f),new Vector3(.13f,.65f,.13f),2,0);g.Oval(hc+new Vector3(side*.15f,.39f,.05f),new Vector3(.07f,.49f,.025f),2,4);}
                else if(name=="rat"||name=="monkey")
                {g.Oval(hc+new Vector3(side*.28f,.15f,0),new Vector3(.24f,.25f,.1f),2,0);g.Oval(hc+new Vector3(side*.28f,.15f,.045f),new Vector3(.15f,.16f,.02f),2,4);}
                else if(name=="dog")g.Oval(hc+new Vector3(side*.25f,-.035f,-.04f),new Vector3(.15f,.45f,.22f),2,6);
                else if(name!="snake"&&name!="rooster")g.Cone(hc+new Vector3(side*.18f,.14f,-.07f),.28f,.10f,2,0);
                if(name=="ox"||name=="goat"||reptile)
                {g.Cone(hc+new Vector3(side*.27f,.1f,-.1f),name=="goat"?.44f:.3f,.075f,2,5);}
                if(name=="pig")g.Oval(hc+new Vector3(side*.07f,-.08f,.38f),new Vector3(.045f,.055f,.025f),2,2);
                if(name=="tiger")for(int stripe=0;stripe<4;stripe++)g.Oval(new Vector3(side*.275f,.7f,-.3f+stripe*.19f),new Vector3(.025f,.33f,.07f),1,2);
                if(reptile||bird)
                {
                    int bone=side<0?3:4;
                    g.Oval(new Vector3(side*(reptile?.5f:.38f),.7f,-.07f),new Vector3(reptile?.85f:.43f,.10f,reptile?.6f:.49f),bone,reptile?6:5,6,3);
                }
            }
            if(!snake)for(int leg=0;leg<4;leg++)
            {
                if(bird&&leg<2)continue;Vector3 p=bones[3+leg].position;
                g.Oval(p+new Vector3(0,-.20f,0),new Vector3(name=="horse"?.13f:.18f,.43f,.20f),3+leg,bird?5:0);
                g.Oval(p+new Vector3(0,-.37f,.065f),new Vector3(.22f,.13f,.29f),3+leg,name=="horse"||name=="ox"||name=="goat"?2:1);
            }
            if(snake)for(int segment=0;segment<5;segment++)g.Oval(new Vector3(Mathf.Sin(segment)*.12f,.30f,-.3f-segment*.18f),new Vector3(.34f-segment*.04f,.23f,.32f),7,segment%2==0?0:6);
            else if(name=="rabbit")g.Oval(new Vector3(0,.68f,-.52f),Vector3.one*.24f,7,3);
            else if(bird)
            {
                for(int i=0;i<5;i++)g.Oval(new Vector3((i-2)*.10f,.84f+Mathf.Abs(i-2)*.05f,-.56f),new Vector3(.12f,.58f,.15f),7,i%2==0?6:0);
                for(int i=0;i<3;i++)g.Oval(hc+new Vector3(0,.27f,.12f-i*.11f),new Vector3(.11f,.24f,.14f),2,4);
                g.Cone(hc+new Vector3(0,-.02f,.3f),.2f,.08f,2,5);
            }
            else
            {
                for(int i=0;i<(reptile?5:3);i++)g.Oval(new Vector3(Mathf.Sin(i*.6f)*.08f,.64f+i*.07f,-.48f-i*.13f),new Vector3(.18f-i*.02f,.15f,.28f),7,name=="rat"?4:0);
            }
            if(name=="horse")for(int i=0;i<5;i++)g.Oval(hc+new Vector3(0,.1f-i*.07f,-.2f),new Vector3(.13f,.18f,.15f),2,2);
            if(name=="goat")g.Cone(hc+new Vector3(0,-.15f,.15f),.25f,.08f,2,1,true);
            if(reptile)for(int i=0;i<5;i++)g.Cone(new Vector3(0,.85f,-.4f+i*.18f),.22f,.08f,1,5);
            var mesh=new Mesh{name=name+" weighted animal"};mesh.SetVertices(g.vertices);mesh.SetUVs(0,g.uv);mesh.SetTriangles(g.indices,0);mesh.boneWeights=g.weights.ToArray();
            var bind=new Matrix4x4[bones.Count];for(int i=0;i<bind.Length;i++)bind[i]=bones[i].worldToLocalMatrix*root.transform.localToWorldMatrix;mesh.bindposes=bind;mesh.RecalculateNormals();mesh.RecalculateBounds();
            var saved=AssetDatabase.LoadAssetAtPath<Mesh>(path+"/Animal.asset");if(saved==null)AssetDatabase.CreateAsset(mesh,path+"/Animal.asset");else{EditorUtility.CopySerialized(mesh,saved);UnityEngine.Object.DestroyImmediate(mesh);mesh=saved;}
            var skin=root.AddComponent<SkinnedMeshRenderer>();skin.sharedMesh=mesh;skin.bones=bones.ToArray();skin.rootBone=skeleton;skin.sharedMaterial=material;skin.updateWhenOffscreen=true;
            var animation=root.AddComponent<Animation>();
            foreach(string clipName in new[]{"Idle","Walk","Attack","Heavy","Dodge","Bow","Throw"})
            {
                string clipPath=path+"/"+clipName+".anim";var clip=AssetDatabase.LoadAssetAtPath<AnimationClip>(clipPath);if(clip==null){clip=new AnimationClip();AssetDatabase.CreateAsset(clip,clipPath);}
                clip.legacy=true;clip.wrapMode=clipName=="Idle"||clipName=="Walk"?WrapMode.Loop:WrapMode.Once;clip.frameRate=30;
                float duration=clipName=="Walk"?.8f:clipName=="Idle"?2f:.6f;
                for(int leg=0;leg<4;leg++)
                {
                    float amount=clipName=="Walk"?27:clipName=="Dodge"?55:clipName=="Idle"?2:leg<2?45:8;
                    float phase=leg==0||leg==3?1:-1;
                    clip.SetCurve("root/torso/leg-"+leg,typeof(Transform),"localEulerAnglesRaw.x",new AnimationCurve(new Keyframe(0,0),new Keyframe(duration*.25f,amount*phase),new Keyframe(duration*.75f,-amount*phase),new Keyframe(duration,0)));
                }
                float swing=clipName=="Idle"?3:clipName=="Walk"?8:35;
                clip.SetCurve("root/torso/head",typeof(Transform),"localEulerAnglesRaw.x",new AnimationCurve(new Keyframe(0,0),new Keyframe(duration*.45f,-swing),new Keyframe(duration,0)));
                clip.SetCurve("root/torso/tail",typeof(Transform),"localEulerAnglesRaw.y",new AnimationCurve(new Keyframe(0,-12),new Keyframe(duration*.5f,12),new Keyframe(duration,-12)));
                animation.AddClip(clip,clipName);if(clipName=="Idle")animation.clip=clip;EditorUtility.SetDirty(clip);
            }
            animation.playAutomatically=true;PrefabUtility.SaveAsPrefabAsset(root,path+"/Character.prefab");UnityEngine.Object.DestroyImmediate(root);EditorUtility.SetDirty(material);
        }
        public static void Verify()
        {
            foreach(string name in Names)
            {
                var prefab=AssetDatabase.LoadAssetAtPath<GameObject>(Folder+"/"+name+"/Character.prefab");if(prefab==null)throw new Exception("Missing "+name);
                var instance=UnityEngine.Object.Instantiate(prefab);var skin=instance.GetComponent<SkinnedMeshRenderer>();var mesh=skin.sharedMesh;
                if(mesh.bindposes.Length!=skin.bones.Length||mesh.uv.Length!=mesh.vertexCount)throw new Exception("Invalid bind poses or UV "+name);
                foreach(var weight in mesh.boneWeights)if(Mathf.Abs(weight.weight0+weight.weight1+weight.weight2+weight.weight3-1)>1e-5)throw new Exception("Invalid weights "+name);
                var before=new Mesh();var after=new Mesh();skin.BakeMesh(before);
                instance.GetComponent<Animation>().GetClip("Walk").SampleAnimation(instance,.2f);skin.BakeMesh(after);
                bool moved=false;var a=before.vertices;var b=after.vertices;for(int i=0;i<a.Length;i++)if((a[i]-b[i]).sqrMagnitude>.00001f){moved=true;break;}
                if(!moved)throw new Exception("No skinned deformation "+name);
                foreach(string clip in new[]{"Idle","Walk","Attack","Heavy","Dodge","Bow","Throw"})if(instance.GetComponent<Animation>().GetClip(clip)==null)throw new Exception("Missing clip "+clip);
                UnityEngine.Object.DestroyImmediate(before);UnityEngine.Object.DestroyImmediate(after);UnityEngine.Object.DestroyImmediate(instance);
            }
        }
        static void RenderCatalog()
        {
            var root=new GameObject("Zodiac catalog");root.transform.position=new Vector3(20000,0,20000);
            var light=new GameObject("Catalog light");light.transform.SetParent(root.transform);light.transform.localRotation=Quaternion.Euler(45,-35,0);var lamp=light.AddComponent<Light>();lamp.type=LightType.Directional;lamp.intensity=2;
            var cameraObject=new GameObject("Catalog camera");cameraObject.transform.SetParent(root.transform);var camera=cameraObject.AddComponent<Camera>();camera.backgroundColor=new Color(.08f,.065f,.14f);camera.clearFlags=CameraClearFlags.SolidColor;camera.orthographic=true;camera.orthographicSize=1.4f;
            var rt=new RenderTexture(320,280,24);camera.targetTexture=rt;var sheet=new Texture2D(1280,840,TextureFormat.RGB24,false);
            for(int i=0;i<12;i++)
            {
                var model=UnityEngine.Object.Instantiate(AssetDatabase.LoadAssetAtPath<GameObject>(Folder+"/"+Names[i]+"/Character.prefab"),root.transform);model.transform.localPosition=Vector3.zero;
                camera.transform.localPosition=new Vector3(2,1.35f,2.4f);camera.transform.LookAt(root.transform.position+Vector3.up*.65f);
                var config=Resources.Load<RetroRenderConfig>("RetroFantasy/RenderConfig");if(config!=null)camera.GetUniversalAdditionalCameraData().SetRenderer(config.rendererIndex);
                camera.Render();var old=RenderTexture.active;RenderTexture.active=rt;var tile=new Texture2D(320,280,TextureFormat.RGB24,false);tile.ReadPixels(new Rect(0,0,320,280),0,0);tile.Apply();RenderTexture.active=old;
                sheet.SetPixels((i%4)*320,(2-i/4)*280,320,280,tile.GetPixels());UnityEngine.Object.DestroyImmediate(tile);UnityEngine.Object.DestroyImmediate(model);
            }
            sheet.Apply();File.WriteAllBytes(Path.Combine(Path.GetTempPath(),"warfront-zodiac-catalog.png"),sheet.EncodeToPNG());camera.targetTexture=null;rt.Release();UnityEngine.Object.DestroyImmediate(rt);UnityEngine.Object.DestroyImmediate(sheet);UnityEngine.Object.DestroyImmediate(root);
        }
